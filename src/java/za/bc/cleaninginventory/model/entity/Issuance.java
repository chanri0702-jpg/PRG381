package za.bc.cleaninginventory.model.entity;
import java.sql.Timestamp;
/**
 *
 * @author chanr
 */
public class Issuance {
    private int issuanceId;
    private int cleanerId;
    private String cleanerName;   
    private int prodId;
    private String productName;   
    private int issuedBy;
    private String issuedByName; 
    private int quantity;
    private Timestamp issueDate;

    public Issuance(int cleanerId, int prodId, int issuedBy, int quantity) {
        this.cleanerId = cleanerId;
        this.prodId = prodId;
        this.issuedBy = issuedBy;
        this.quantity = quantity;
    }
    
    public Issuance() {
    }

    public int getIssuanceId() {
        return issuanceId;
    }

    public void setIssuanceId(int issuanceId) {
        this.issuanceId = issuanceId;
    }

    public int getCleanerId() {
        return cleanerId;
    }

    public void setCleanerId(int cleanerId) {
        this.cleanerId = cleanerId;
    }

    public String getCleanerName() {
        return cleanerName;
    }

    public void setCleanerName(String cleanerName) {
        this.cleanerName = cleanerName;
    }

    public int getProdId() {
        return prodId;
    }

    public void setProdId(int prodId) {
        this.prodId = prodId;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public int getIssuedBy() {
        return issuedBy;
    }

    public void setIssuedBy(int issuedBy) {
        this.issuedBy = issuedBy;
    }

    public String getIssuedByName() {
        return issuedByName;
    }

    public void setIssuedByName(String issuedByName) {
        this.issuedByName = issuedByName;
    }

    public int getQuantity() {
        return quantity;
    }

    public void setQuantity(int quantity) {
        this.quantity = quantity;
    }

    public Timestamp getIssueDate() {
        return issueDate;
    }

    public void setIssueDate(Timestamp issueDate) {
        this.issueDate = issueDate;
    }
}
